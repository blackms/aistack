/**
 * Agent exporter — transforms in-memory AgentDefinition objects into Claude
 * Code native subagent markdown files (`.claude/agents/*.md`).
 *
 * Each generated markdown is standalone (no NPM/MCP dependency required) and
 * carries YAML frontmatter compatible with Claude Code's `/agents` UI:
 *   - name (kebab-case, prefixed `aistack-`)
 *   - description (1-line summary)
 *   - model (claude model alias: `sonnet` | `opus` | `haiku`)
 *   - color (UI accent color for the subagent)
 *   - tools (whitelist; omit to inherit all)
 *
 * Forbidden frontmatter keys per task scope: hooks, mcpServers, permissionMode.
 *
 * This module is intentionally side-effect free at import time so it can be
 * reused by the plugin marketplace builder (AIG-629a/b) to emit identical
 * markdown into `plugin/agents/` instead of `.claude/agents/`.
 */

import { mkdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import type { AgentDefinition } from '../types.js';
import { listAgentDefinitions } from './registry.js';

/** Claude Code model aliases supported in subagent frontmatter. */
export type ClaudeModel = 'sonnet' | 'opus' | 'haiku';

/** Per-agent export overrides keyed by `AgentDefinition.type`. */
interface AgentExportProfile {
  model: ClaudeModel;
  color: string;
  /** Whitelist of Claude Code tools the subagent may use. */
  tools: string[];
}

