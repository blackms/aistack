/** Conservative fallback for custom/unknown agents. */
const FALLBACK_PROFILE: AgentExportProfile = {
  model: 'sonnet',
  color: 'blue',
  tools: ['Read', 'Grep', 'Glob'],
};

/** Prefix applied to every exported subagent name to avoid collisions. */
export const AGENT_NAME_PREFIX = 'aistack-';

export interface ExportAgentOptions {
  /**
   * Override the default profile for a given agent type. Useful for tests and
   * for the plugin marketplace builder that may want different tool sets.
   */
  profiles?: Record<string, Partial<AgentExportProfile>>;
}

/**
 * Convert one AgentDefinition into a Claude Code subagent markdown document.
 * Pure function — no filesystem side effects.
 */
export function exportAgentToMarkdown(
  agent: AgentDefinition,
  options: ExportAgentOptions = {},
): string {
  const base = DEFAULT_PROFILES[agent.type] ?? FALLBACK_PROFILE;
  const override = options.profiles?.[agent.type] ?? {};
  const profile: AgentExportProfile = {
    model: override.model ?? base.model,
    color: override.color ?? base.color,
    tools: override.tools ?? base.tools,
  };

  const name = `${AGENT_NAME_PREFIX}${agent.type}`;
  const description = singleLine(agent.description);

  const frontmatter = [
    '---',
    `name: ${name}`,
    `description: ${yamlString(description)}`,
    `model: ${profile.model}`,
    `color: ${profile.color}`,
    `tools: ${formatToolList(profile.tools)}`,
    '---',
  ].join('\n');

  const header = `# ${agent.name}`;
  const intro =
    `> Exported from the aistack agent registry (type: \`${agent.type}\`).\n` +
    `> Generated by \`aistack export-agents\` — see https://github.com/blackms/aistack.\n` +
    `> This file is standalone: it does not require the aistack NPM package to be installed.`;

  const capabilities = agent.capabilities.length > 0
    ? `## Capabilities\n\n${agent.capabilities.map((c) => `- ${c}`).join('\n')}`
    : '';

  const body = agent.systemPrompt.trimEnd();

  const parts = [frontmatter, '', header, '', intro, ''];
  if (capabilities) {
    parts.push(capabilities, '');
  }
  parts.push(body, '');

  return parts.join('\n');
}

/**
 * Write all registered agent definitions into `outputDir` as
 * `aistack-<type>.md`. Creates the directory if missing.
 *
 * Returns the absolute paths of the files written, in deterministic order.
 */
export async function exportAllAgents(
  outputDir: string,
  options: ExportAgentOptions = {},
): Promise<string[]> {
  await mkdir(outputDir, { recursive: true });

  const definitions = listAgentDefinitions();
  // Sort for deterministic output (test stability + clean diffs)
  const ordered = [...definitions].sort((a, b) => a.type.localeCompare(b.type));

  const written: string[] = [];
  for (const def of ordered) {
    const filename = `${AGENT_NAME_PREFIX}${def.type}.md`;
    const filepath = join(outputDir, filename);
    const content = exportAgentToMarkdown(def, options);
    await writeFile(filepath, content, 'utf8');
    written.push(filepath);
  }

  return written;
}

// ---------------------------------------------------------------------------
// helpers
// ---------------------------------------------------------------------------

function singleLine(input: string): string {
  return input.replace(/\s+/g, ' ').trim();
}

/**
 * YAML-safe string emitter. Always quotes to avoid surprises with special
 * characters (`:`, `#`, leading `-`, etc.) inside descriptions.
 */
function yamlString(value: string): string {
  const escaped = value.replace(/\\/g, '\\\\').replace(/"/g, '\\"');
  return `"${escaped}"`;
}

/** Render a tool list as a YAML flow sequence: `[Read, Edit, Bash]`. */
function formatToolList(tools: string[]): string {
  return `[${tools.join(', ')}]`;
}
